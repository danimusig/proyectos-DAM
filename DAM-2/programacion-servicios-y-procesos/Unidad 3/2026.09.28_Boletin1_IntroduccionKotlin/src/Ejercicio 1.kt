fun main() {
    val valor1 : Int = 10
    val valor2 : Int = 15

    val superficieRectangulo : Int = (valor1 * valor2)
    val perimetroRectangulo : Int = 2 * (valor1 + valor2)

    println("Superficie del cuadrado : " + superficieRectangulo)
    println("Perimetro de un rectangulo: " + perimetroRectangulo)
}

